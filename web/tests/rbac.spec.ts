import { test, expect } from '@playwright/test'

test('ERP 新建角色、配置权限并新建后台人员', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  const suffix = String(Date.now())
  await page.goto('http://127.0.0.1:5173/login')
  await page.getByPlaceholder('请输入账号').fill('catalog_admin')
  await page.getByPlaceholder('请输入密码').fill('CatalogTest123!')
  await page.getByRole('button', { name: /登\s*录/ }).click()
  await expect(page).toHaveURL(/dashboard/)
  await page.getByRole('menuitem', { name: '角色权限', exact: true }).click()
  await page.getByRole('button', { name: '新增角色', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('角色名称', { exact: true }).fill('浏览器角色' + suffix)
  await dialog.getByLabel('角色编码', { exact: true }).fill('browser_' + suffix)
  await dialog.getByText('选择可访问菜单和操作权限', { exact: true }).click()
  await page.getByRole('treeitem', { name: '商城会员', exact: true }).getByText('商城会员', { exact: true }).click()
  await expect(page.getByRole('treeitem', { name: '商城会员', exact: true }).getByRole('checkbox')).toBeChecked()
  await dialog.getByLabel('角色名称', { exact: true }).click()
  await dialog.getByRole('button', { name: '保存角色', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: '浏览器角色' + suffix })).toBeVisible()
  await page.getByRole('menuitem', { name: '后台人员', exact: true }).click()
  await page.getByRole('button', { name: '新增人员', exact: true }).click()
  await dialog.getByLabel('账号', { exact: true }).fill('browser_staff_' + suffix)
  await dialog.getByLabel('姓名/昵称', { exact: true }).fill('浏览器测试人员')
  await dialog.getByLabel('密码', { exact: true }).fill('BrowserStaff123!')
  await dialog.getByText('选择启用角色', { exact: true }).click()
  await page.getByRole('option', { name: '浏览器角色' + suffix, exact: true }).click()
  await page.keyboard.press('Escape')
  await dialog.getByRole('button', { name: '保存人员', exact: true }).click()
  await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'browser_staff_' + suffix })).toBeVisible()
  await page.screenshot({ path: '../server/.runtime/erp-staff.png', fullPage: true })
  await page.getByRole('row').filter({ hasText: 'browser_staff_' + suffix }).getByRole('button', { name: '编辑', exact: true }).click()
  await dialog.getByLabel('姓名/昵称', { exact: true }).fill('已编辑测试人员')
  await dialog.getByRole('button', { name: '保存人员', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'browser_staff_' + suffix })).toContainText('已编辑测试人员')
  await page.getByRole('row').filter({ hasText: 'browser_staff_' + suffix }).getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'browser_staff_' + suffix })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '角色权限', exact: true }).click()
  await page.getByRole('row').filter({ hasText: '浏览器角色' + suffix }).getByRole('button', { name: '删除', exact: true }).click()
  await page.getByRole('button', { name: '确定', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: '浏览器角色' + suffix })).toHaveCount(0)
  await page.getByRole('menuitem', { name: '菜单权限', exact: true }).click()
  await expect(page.getByText('商城会员', { exact: true }).last()).toBeVisible()
  await page.screenshot({ path: '../server/.runtime/erp-menu-permissions.png', fullPage: true })
  expect(errors).toEqual([])
})
